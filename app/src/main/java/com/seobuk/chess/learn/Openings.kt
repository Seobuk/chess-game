    fun byId(id: String): Opening? = all.firstOrNull { it.id == id }

    /** The most specific opening (largest keyPlies) whose first keyPlies moves match the game so far. */
    fun detect(playedUci: List<String>): Opening? = all
        .filter { it.keyPlies <= playedUci.size && it.matches(playedUci, it.keyPlies) }
        .maxByOrNull { it.keyPlies }

    /** Distinct next moves (UCI) from every line that starts with [playedUci]. Includes trap lines. */
    fun continuations(playedUci: List<String>): List<String> = all
        .filter { it.steps.size > playedUci.size && it.matches(playedUci, playedUci.size) }
        .map { it.steps[playedUci.size].uci }
        .distinct()

    private fun Opening.matches(played: List<String>, plies: Int): Boolean =
        (0 until plies).all { steps[it].uci == played[it] }
}

private fun line(vararg steps: Pair<String, String>): List<OpeningStep> =
    steps.map { OpeningStep(it.first, it.second) }
